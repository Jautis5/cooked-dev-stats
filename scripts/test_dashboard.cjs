const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..','site');
const src=fs.readFileSync(path.join(root,'app.js'),'utf8').split("window.addEventListener('hashchange'")[0];
const api=vm.runInNewContext(src+'\n({compact,total,summary,combine,videoTitle,changeFor})',{Intl,URL,Date,location:{href:'https://example.com/',hash:''}});
const data=JSON.parse(fs.readFileSync(path.join(root,'data/latest.json')));
const fixture={accounts:[{id:'instagram',metrics:{followers:{value:10}}},{id:'tiktok',metrics:{followers:{value:20}}}],videos:[{posts:{instagram:{metrics:{views:{value:100},likes:{value:5}}},tiktok:{metrics:{views:{value:150},likes:{value:6}}}}},{posts:{tiktok:{metrics:{views:{value:200}}}}}]};
const s=api.summary(fixture);
assert.equal(s.views.value,450);assert.equal(s.postCount,3);assert.equal(s.videoCount,2);assert.equal(s.followers.value,30);assert.equal(s.likes.count,2);
const both=api.combine([s,s]);assert.equal(both.views.value,900);assert.equal(both.postCount,6);assert.equal(both.accountCount,4);
assert.equal(api.total([{metrics:{views:{value:0}}},{metrics:{}}],'views').value,0);
assert.equal(api.total([{metrics:{}}],'views').value,null);
assert.equal(api.total([{metrics:{views:{value:12,approximate:true}}}],'views').approximate,true);
assert.equal(api.summary(fixture,'tiktok').views.value,350);
assert.equal(api.summary(fixture,'instagram').views.value,100);
const unverified={accounts:[{id:'x',metrics:{publishedCount:{value:0}}}],videos:[]};assert.equal(api.summary(unverified).views.value,null);
const indian=JSON.parse(fs.readFileSync(path.join(root,'data/indian-builds.json')));
assert.equal(api.summary(indian).views.value,0);
assert.equal(api.summary(indian).followers.value,0);
assert.equal(api.summary(indian).postCount,0);
assert.ok(indian.tracking.excludedPostIds.tiktok.length>=16);
assert.ok(indian.accounts.filter(a=>['instagram','tiktok'].includes(a.id)).every(a=>a.expectedHandle==='indiaanbuilds'));
assert.equal(indian.accounts.find(a=>a.id==='facebook').expectedPageId,'61594164374065');
assert.equal(indian.accounts.find(a=>a.id==='x').url,'https://x.com/IndiaanBuilds');
assert.equal(indian.accounts.find(a=>a.id==='youtube').expectedChannelId,'UCgHxdk2zTRXwsoCrICSwiRg');
assert.equal(api.combine([s,api.summary(indian)]).views.value,s.views.value);
for(const [n,expected] of [[243830,'243.8K'],[10618,'10.6K'],[1500000,'1.5M'],[999999,'1M'],[0,'0'],[null,'—']])assert.equal(api.compact(n),expected);
assert.equal(api.changeFor(data,'views'),null);
assert.equal(api.changeFor({changes24h:{views:{value:5,comparable:true,at:new Date(Date.now()+60000).toISOString()}}},'views'),null);
for(const v of data.videos)assert.ok(!/[ąčęėįšųūž]/i.test(api.videoTitle(v)),'English video title required');
assert.ok(data.videos.filter(v=>v.assetUrl?.startsWith('https://drive.google.com/')).length>=12);
const channels=JSON.parse(fs.readFileSync(path.join(root,'data/channels.json'))).channels;
assert.equal(new Set(channels.map(c=>c.id)).size,channels.length);
const indianConfig=channels.find(c=>c.id==='indian-builds');
assert.ok(indianConfig.assetLibraryUrl.endsWith('1WEHFKQCzbjUcPzm7nYB3PthPngxLXYGR'));
assert.ok(indianConfig.dataUrl.endsWith('/data/indian-builds/latest.json'));
assert.ok(indianConfig.sheetUrl.endsWith('#gid=785807837'));
console.log('PASS: channel aggregation, compact counts, missing vs zero, honest 24h changes, English titles and 12 Drive links.');
